"""Re-inject common interactive behaviour with dependency-free vanilla JS.

When the original framework runtime is stripped (the default, to get a stable
static snapshot), the captured DOM is inert.  This module ships a single
``interactions.js`` that heuristically re-wires the most common patterns -
mobile nav toggles, dropdowns, accordions/FAQ, tabs, modals, smooth anchor
scrolling and scroll-reveal animations - by inspecting the markup that is
present.  It is intentionally conservative: it only acts on recognised markers.
"""
from __future__ import annotations

from app.models.domain import RenderedPage

INTERACTIONS_JS = r"""/*
 * interactions.js - generated by the Universal Website Replication Engine.
 * Dependency-free re-implementation of common UI behaviours for the copy.
 *
 * Safe to call several times: window.ReplicatorInteractions.init() binds each
 * element once (used by the React / Next.js outputs after every navigation).
 */
(function () {
  "use strict";
  if (window.ReplicatorInteractions) { window.ReplicatorInteractions.init(); return; }
  var bound = typeof WeakSet !== "undefined" ? new WeakSet() : null;
  function once(el, key) {
    if (!bound) { if (el["__rx" + key]) return false; el["__rx" + key] = 1; return true; }
    var k = el; if (!el.__rxKeys) el.__rxKeys = {};
    if (el.__rxKeys[key]) return false; el.__rxKeys[key] = 1; bound.add(k); return true;
  }
  function $(sel, ctx) { try { return Array.prototype.slice.call((ctx || document).querySelectorAll(sel)); } catch (e) { return []; } }
  function toggleClass(el, cls) { if (el) el.classList.toggle(cls); }
  var io = null;

  // 0. Classes the original JavaScript toggled per breakpoint (captured per
  //    viewport, stored on <body data-rx-bp>), replayed on load and resize.
  var bpRows = null;
  function applyBreakpoints() {
    if (bpRows === null) {
      try { bpRows = JSON.parse(document.body.getAttribute("data-rx-bp") || "[]"); } catch (e) { bpRows = []; }
    }
    if (!bpRows.length) return;
    var w = window.innerWidth, all = { h: {}, b: {} };
    bpRows.forEach(function (r) {
      r[2].concat(r[3]).forEach(function (c) { all.h[c] = 1; });
      r[4].concat(r[5]).forEach(function (c) { all.b[c] = 1; });
    });
    var row = null;
    bpRows.forEach(function (r) { if (w >= r[0] && (r[1] === null || w <= r[1])) row = r; });
    if (!row) return;
    var de = document.documentElement.classList, bd = document.body.classList;
    // Reset every toggled class to the serialised state, then apply this range.
    bpRows.forEach(function (r) {
      r[2].forEach(function (c) { de.remove(c); }); r[3].forEach(function (c) { de.add(c); });
      r[4].forEach(function (c) { bd.remove(c); }); r[5].forEach(function (c) { bd.add(c); });
    });
    row[2].forEach(function (c) { de.add(c); }); row[3].forEach(function (c) { de.remove(c); });
    row[4].forEach(function (c) { bd.add(c); }); row[5].forEach(function (c) { bd.remove(c); });
  }
  var bpTimer = null;
  window.addEventListener("resize", function () { clearTimeout(bpTimer); bpTimer = setTimeout(applyBreakpoints, 60); });

  function init() {
    applyBreakpoints();
    // 1. Mobile nav / hamburger toggles.
    var toggleSelectors = [
      "[data-toggle='menu']", ".hamburger", ".menu-toggle", ".navbar-toggle",
      ".navbar-toggler", ".nav-toggle", ".burger", "[aria-label*='menu' i]",
      "button[aria-controls]"
    ];
    $(toggleSelectors.join(",")).forEach(function (btn) {
      if (!once(btn, "nav")) return;
      btn.addEventListener("click", function (e) {
        var target = null;
        var controls = btn.getAttribute("aria-controls");
        if (controls) target = document.getElementById(controls);
        if (!target) target = document.querySelector("nav ul, .nav-menu, .menu, .navbar-collapse, nav");
        if (target) {
          e.preventDefault();
          toggleClass(target, "is-open");
          target.classList.toggle("open");
          var expanded = btn.getAttribute("aria-expanded") === "true";
          btn.setAttribute("aria-expanded", String(!expanded));
          btn.classList.toggle("is-active");
          document.body.classList.toggle("nav-open");
        }
      });
    });

    // 2. Accordions / FAQ (aria-expanded buttons + common classes).
    $("[aria-expanded]").forEach(function (btn) {
      if (btn.closest("nav") || !once(btn, "acc")) return;
      btn.addEventListener("click", function () {
        var expanded = btn.getAttribute("aria-expanded") === "true";
        btn.setAttribute("aria-expanded", String(!expanded));
        var controls = btn.getAttribute("aria-controls");
        var panel = controls ? document.getElementById(controls) : btn.nextElementSibling;
        if (panel) { panel.hidden = expanded; panel.classList.toggle("open", !expanded); }
      });
    });
    $(".accordion-header, .faq-question, .accordion__title, [data-accordion] > *:first-child").forEach(function (head) {
      if (!once(head, "acc2")) return;
      head.addEventListener("click", function () {
        var panel = head.nextElementSibling;
        toggleClass(head.parentElement, "open");
        if (panel) toggleClass(panel, "open");
      });
    });
    $("details > summary").forEach(function () { /* native */ });

    // 3. Tabs (role=tab + aria-controls).
    $("[role='tab']").forEach(function (tab) {
      if (!once(tab, "tab")) return;
      tab.addEventListener("click", function (e) {
        e.preventDefault();
        var list = tab.closest("[role='tablist']") || document;
        $("[role='tab']", list).forEach(function (t) {
          t.setAttribute("aria-selected", "false"); t.classList.remove("active");
          var c = t.getAttribute("aria-controls"); var p = c && document.getElementById(c);
          if (p) p.hidden = true;
        });
        tab.setAttribute("aria-selected", "true"); tab.classList.add("active");
        var controls = tab.getAttribute("aria-controls");
        var panel = controls && document.getElementById(controls);
        if (panel) panel.hidden = false;
      });
    });

    // 4. Modals / dialogs via data-attributes.
    $("[data-modal-target], [data-toggle='modal']").forEach(function (trigger) {
      if (!once(trigger, "modal")) return;
      trigger.addEventListener("click", function (e) {
        e.preventDefault();
        var sel = trigger.getAttribute("data-modal-target") || trigger.getAttribute("data-target");
        var modal = null; try { modal = sel && document.querySelector(sel); } catch (err) {}
        if (modal) { modal.classList.add("open"); modal.removeAttribute("hidden"); modal.style.display = "block"; }
      });
    });
    $("[data-modal-close], .modal .close, .modal__close").forEach(function (closer) {
      if (!once(closer, "close")) return;
      closer.addEventListener("click", function () {
        var modal = closer.closest(".modal, [role='dialog']");
        if (modal) { modal.classList.remove("open"); modal.style.display = "none"; }
      });
    });

    // 5. Smooth anchor scrolling ("#" links are inert placeholders).
    $("a[href^='#']").forEach(function (a) {
      if (!once(a, "anchor")) return;
      a.addEventListener("click", function (e) {
        var id = a.getAttribute("href").slice(1);
        if (!id) { e.preventDefault(); return; }
        var target = document.getElementById(id) || document.querySelector("[name='" + id.replace(/'/g, "") + "']");
        if (target) { e.preventDefault(); target.scrollIntoView({ behavior: "smooth" }); }
      });
    });

    // 6. Scroll-reveal: reveal elements marked for animation once in view.
    var revealEls = $("[data-aos],[data-animate],.reveal,.fade-in,.animate-on-scroll,.wow");
    if (revealEls.length && "IntersectionObserver" in window) {
      if (!io) {
        io = new IntersectionObserver(function (entries) {
          entries.forEach(function (en) {
            if (en.isIntersecting) { en.target.classList.add("in-view", "aos-animate"); io.unobserve(en.target); }
          });
        }, { threshold: 0.12 });
      }
      revealEls.forEach(function (el) { if (once(el, "reveal")) io.observe(el); });
    } else {
      revealEls.forEach(function (el) { el.classList.add("in-view", "aos-animate"); });
    }

    // 7. Forms: no live backend - validate, then confirm locally.
    $("form").forEach(function (form) {
      if (form.getAttribute("data-replicator-keep") || !once(form, "form")) return;
      form.addEventListener("submit", function (e) {
        if (!form.checkValidity || form.checkValidity()) {
          e.preventDefault();
          form.classList.add("replicator-submitted");
          var note = form.querySelector(".replicator-note");
          if (!note) {
            note = document.createElement("p");
            note.className = "replicator-note";
            note.style.cssText = "margin-top:.75rem;font-size:.9rem;";
            note.textContent = "Merci, votre message a bien été pris en compte.";
            form.appendChild(note);
          }
        }
      });
    });

    document.documentElement.classList.add("replicator-interactions-ready");
  }

  window.ReplicatorInteractions = { init: init };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
"""


def interaction_report(pages: list[RenderedPage]) -> dict:
    """Summarise which interactive patterns were detected across the site."""
    markers = {
        "mobile_nav": ["hamburger", "menu-toggle", "navbar-toggle", "nav-toggle", "aria-controls"],
        "accordion": ["accordion", "faq", "aria-expanded"],
        "tabs": ["role=\"tab\"", "role='tab'", "nav-tabs"],
        "modal": ["data-modal", "data-toggle=\"modal\"", "role=\"dialog\""],
        "carousel": ["swiper", "slick", "carousel", "splide", "glide"],
        "scroll_reveal": ["data-aos", "data-animate", "animate-on-scroll", "wow"],
    }
    detected: dict[str, int] = {k: 0 for k in markers}
    for p in pages:
        low = (p.html or "").lower()
        for name, keys in markers.items():
            if any(k in low for k in keys):
                detected[name] += 1
    return {k: v for k, v in detected.items() if v}
