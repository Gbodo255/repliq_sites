def interaction_report(pages: list[RenderedPage]) -> dict:
    """Summarise which interactive patterns were detected / reproduced.

    Markup markers show which patterns exist; ``reveals`` and ``scroll_state``
    count what the renderer actually captured by effect (so they reflect real
    animations re-played on the copy, not just library names in the HTML).
    """
    markers = {
        "mobile_nav": ["hamburger", "menu-toggle", "navbar-toggle", "nav-toggle", "aria-controls"],
        "accordion": ["accordion", "faq", "aria-expanded"],
        "tabs": ["role=\"tab\"", "role='tab'", "nav-tabs"],
        "modal": ["data-modal", "data-toggle=\"modal\"", "role=\"dialog\""],
        "carousel": ["swiper", "slick", "carousel", "splide", "glide"],
        "scroll_reveal": ["data-aos", "data-animate", "animate-on-scroll", "wow"],
    }
    detected: dict[str, int] = {k: 0 for k in markers}
    reveals = 0
    scroll_state_pages = 0
    for p in pages:
        low = (p.html or "").lower()
        for name, keys in markers.items():
            if any(k in low for k in keys):
                detected[name] += 1
        reveals += len((p.analysis or {}).get("reveal") or [])
        if ((p.analysis or {}).get("scroll_state") or {}).get("rows"):
            scroll_state_pages += 1
    report = {k: v for k, v in detected.items() if v}
    if reveals:
        report["reveals_captured"] = reveals
    if scroll_state_pages:
        report["scroll_state_pages"] = scroll_state_pages
    return report
