"""Re-inject common interactive behaviour with dependency-free vanilla JS.

When the original framework runtime is stripped (the default, to get a stable
static snapshot), the captured DOM is inert.  This module ships a single
``interactions.js`` that re-wires the most common patterns so the offline copy
behaves and animates like the original:

* **Scroll-reveal animations** replayed from the motion the renderer captured by
  *effect* (``data-rx-reveal`` table + ``data-rx-reveal-i`` markers): each
  element fades / slides in on scroll with its real initial state and
  transition, independently of the library that produced it (AOS, WOW, GSAP,
  Framer, custom IntersectionObserver...).
* **Scroll-state classes** (``data-rx-scroll``): sticky / shrinking headers and
  "scrolled" navs get the classes the original JavaScript toggled, so the site's
  own CSS drives the effect.
* **Carousels / sliders** (Swiper, Slick, Splide, Glide, Bootstrap, generic):
  a dependency-free engine restores prev/next, pagination dots, looping and
  autoplay.
* **Breakpoint classes** (``data-rx-bp``) the original JS set per viewport.
* Mobile nav toggles, dropdowns, accordions / FAQ, tabs, modals, smooth anchor
  scrolling and offline form handling.

It is conservative (only acts on recognised markers / captured data), reversible
and respects ``prefers-reduced-motion``. ``window.ReplicatorInteractions.freeze``
forces every animation to its resolved state for deterministic quality shots.
"""
